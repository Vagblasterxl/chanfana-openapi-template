#!/usr/bin/env bash
# Deny Edit/Write that would put a live key into a tracked file, or touch .dev.vars.
node -e '
let d="";process.stdin.on("data",c=>d+=c).on("end",()=>{
  let j={};try{j=JSON.parse(d)}catch{}
  const t=j.tool_input||{}; const p=String(t.file_path||"");
  const body=[t.content,t.new_string,...(t.edits||[]).map(e=>e.new_string)].filter(Boolean).join("\n");
  if (/(^|\/)\.dev\.vars$/.test(p)) { console.error("BLOCKED: .dev.vars holds real secrets; edit it by hand, not via Claude."); process.exit(2); }
  if (/(^|\/)(package-lock\.json|pnpm-lock\.yaml)$/.test(p)) { console.error("BLOCKED: lockfiles are regenerated by npm/pnpm, never hand-edited."); process.exit(2); }
  if (/sk-mem-[0-9a-f]{8}|sk-ant-|ghp_[A-Za-z0-9]{20}|AKIA[0-9A-Z]{16}/.test(body) && !/\.dev\.vars/.test(p)) {
    console.error("BLOCKED: that content contains a real-looking API key. Keys go in .dev.vars or wrangler secret, never in tracked files."); process.exit(2);
  }
  process.exit(0);
});'
